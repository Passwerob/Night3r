#!/usr/bin/env python3
"""Validate and summarize a generated DL3DV DA3 pseudo-depth dataset."""

import argparse
import json
import os
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw, ImageFont, ImageOps


def parse_args():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, required=True)
    parser.add_argument("--allow-incomplete", action="store_true")
    return parser.parse_args()


def read_json(path):
    with open(path, "r") as handle:
        return json.load(handle)


def atomic_write(path, content):
    tmp = path.with_suffix(path.suffix + f".tmp.{os.getpid()}")
    with open(tmp, "w") as handle:
        handle.write(content)
    os.replace(tmp, path)


def make_contact_sheet(root, complete):
    chosen = complete[:: max(1, len(complete) // 12)][:12]
    if not chosen:
        return None
    tile_w, tile_h = 630, 371
    label_h = 24
    columns = 2
    rows = (len(chosen) + columns - 1) // columns
    sheet = Image.new("RGB", (columns * tile_w, rows * (tile_h + label_h)), "white")
    draw = ImageDraw.Draw(sheet)
    font = ImageFont.load_default()
    for index, item in enumerate(chosen):
        row, column = divmod(index, columns)
        x = column * tile_w
        y = row * (tile_h + label_h)
        image = Image.open(root / item["scene"] / "pseudo_depth_overview.jpg").convert("RGB")
        image = ImageOps.fit(image, (tile_w, tile_h), method=Image.Resampling.LANCZOS)
        sheet.paste(image, (x, y + label_h))
        draw.text(
            (x + 6, y + 6),
            f"{item['scene']}  source={item['source_scene']} clip={item['source_clip']}",
            fill="black",
            font=font,
        )
    output = root / "pseudo_depth_contact_sheet.jpg"
    sheet.save(output, quality=94)
    return output


def main():
    args = parse_args()
    selection = read_json(args.root / "selection_manifest.json")
    complete = []
    incomplete = []
    for record in selection["records"]:
        scene_dir = args.root / record["scene"]
        manifest_path = scene_dir / "pseudo_depth_manifest.json"
        if not manifest_path.is_file():
            incomplete.append({"scene": record["scene"], "reason": "missing manifest"})
            continue
        manifest = read_json(manifest_path)
        depth_count = len(list((scene_dir / "depth_pseudo").glob("*.pt")))
        conf_count = len(list((scene_dir / "depth_pseudo_conf").glob("*.pt")))
        if (
            manifest.get("status") != "complete"
            or depth_count != record["image_count"]
            or conf_count != record["image_count"]
        ):
            incomplete.append(
                {
                    "scene": record["scene"],
                    "reason": "incomplete files",
                    "depth_count": depth_count,
                    "conf_count": conf_count,
                    "expected": record["image_count"],
                }
            )
            continue
        complete.append(manifest)

    summary = {
        "status": "complete" if not incomplete else "incomplete",
        "label_type": "DA3 pseudo depth; not sensor/dataset ground truth",
        "selected_clip_count": selection["selected_clip_count"],
        "selected_frame_count": selection["selected_frame_count"],
        "complete_clip_count": len(complete),
        "complete_frame_count": sum(item["frame_count"] for item in complete),
        "incomplete": incomplete,
        "excluded_test_source_scenes": selection["excluded_test_source_scenes"],
        "selected_source_scenes": sorted({item["source_scene"] for item in complete}),
        "depth_median_across_clips": (
            float(np.median([item["depth_median"] for item in complete])) if complete else None
        ),
        "valid_fraction_mean": (
            float(np.mean([item["valid_fraction"] for item in complete])) if complete else None
        ),
        "generation_elapsed_scene_seconds": (
            float(sum(item["elapsed_seconds"] for item in complete)) if complete else 0.0
        ),
    }
    atomic_write(args.root / "generation_summary.json", json.dumps(summary, indent=2) + "\n")
    contact = make_contact_sheet(args.root, complete)

    readme = f"""# DL3DV DA3 pseudo-depth subset

This directory contains pose-conditioned pseudo-depth labels generated by
`DA3-LARGE-1.1` from clean DL3DV RGB frames.

- Selected clips: `{summary['complete_clip_count']}/{summary['selected_clip_count']}`
- Selected frames: `{summary['complete_frame_count']}/{summary['selected_frame_count']}`
- Source scenes: `{len(summary['selected_source_scenes'])}`
- Test-source overlap: `0` by construction
- Saved depth shape: `512 x 512`
- Input pose convention: DL3DV OpenGL camera-to-world converted to OpenCV world-to-camera
- Scale policy: DA3 predictions aligned to the supplied DL3DV extrinsic scale, followed by overlap-window scale stabilization

## Important

These maps are **pseudo depth**, not sensor or dataset ground truth. They are
stored under `depth_pseudo/`, with raw DA3 confidence under
`depth_pseudo_conf/`. Night3R uses a separate confidence-masked,
median-scale-aligned distillation loss and leaves the real `depth_gt` loss
unchanged.

The `images/`, `events/`, and `transforms.json` entries inside each selected
scene are symlinks to the original training data. Per-scene generation details
are recorded in `pseudo_depth_manifest.json`.

Model license: `DA3-LARGE-1.1` is released under CC BY-NC 4.0.
"""
    if contact is not None:
        readme += "\nOverview: `pseudo_depth_contact_sheet.jpg`.\n"
    atomic_write(args.root / "README.md", readme)
    print(json.dumps(summary, indent=2))
    if incomplete and not args.allow_incomplete:
        raise SystemExit(1)


if __name__ == "__main__":
    main()
